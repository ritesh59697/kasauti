// Copies the compiled Kasauti ABI (and creation bytecode, used only by the local deploy page) into the
// frontend so the UI never drifts from the contract.
import { readFileSync, writeFileSync } from "node:fs";
const art = JSON.parse(readFileSync(new URL("../contracts/out/Kasauti.sol/Kasauti.json", import.meta.url)));
const head = "// Generated by scripts/export-abi.mjs from contracts/out. Do not edit.\n";
writeFileSync(
  new URL("../web/src/lib/kasautiAbi.ts", import.meta.url),
  `${head}export const kasautiAbi = ${JSON.stringify(art.abi, null, 2)} as const;\n`,
);
writeFileSync(
  new URL("../web/src/lib/kasautiBytecode.ts", import.meta.url),
  `${head}export const kasautiBytecode = ${JSON.stringify(art.bytecode.object)} as const;\n`,
);
console.log(`kasautiAbi: ${art.abi.length} entries, bytecode ${(art.bytecode.object.length - 2) / 2} bytes`);
