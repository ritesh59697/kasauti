// Copies the compiled Kasauti ABI into the frontend so the UI never drifts from the contract.
import { readFileSync, writeFileSync } from "node:fs";
const art = JSON.parse(readFileSync(new URL("../contracts/out/Kasauti.sol/Kasauti.json", import.meta.url)));
writeFileSync(
  new URL("../web/src/lib/kasautiAbi.ts", import.meta.url),
  `// Generated by scripts/export-abi.mjs from contracts/out. Do not edit.\nexport const kasautiAbi = ${JSON.stringify(art.abi, null, 2)} as const;\n`,
);
console.log(`kasautiAbi: ${art.abi.length} entries`);
